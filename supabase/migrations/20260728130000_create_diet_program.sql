alter table public.registrations
  add column if not exists target_weight numeric(6, 2),
  add column if not exists program_status text not null default 'registered',
  add column if not exists started_at timestamptz,
  add column if not exists ended_at timestamptz,
  add column if not exists test_mode boolean not null default true;

alter table public.registrations
  drop constraint if exists registrations_target_weight_check;
alter table public.registrations
  add constraint registrations_target_weight_check
  check (
    target_weight is null
    or (target_weight > 0 and target_weight <= 999.9 and target_weight < weight)
  );

alter table public.registrations
  drop constraint if exists registrations_program_status_check;
alter table public.registrations
  add constraint registrations_program_status_check
  check (program_status in ('registered', 'active', 'continuing', 'ended'));

alter table public.weight_entries
  add column if not exists checkin_type text,
  add column if not exists feedback_sent_at timestamptz;

create unique index if not exists weight_entries_registration_checkin_key
  on public.weight_entries (registration_id, checkin_type)
  where checkin_type is not null;

create table if not exists public.scheduled_program_emails (
  id bigint generated by default as identity primary key,
  registration_id bigint not null references public.registrations(id) on delete cascade,
  milestone text not null,
  resend_email_id text,
  scheduled_for timestamptz not null,
  status text not null default 'scheduled'
    check (status in ('scheduled', 'cancel_requested', 'canceled')),
  created_at timestamptz not null default now(),
  unique (registration_id, milestone)
);

alter table public.scheduled_program_emails enable row level security;
revoke all on table public.scheduled_program_emails from anon, authenticated;
revoke all on sequence public.scheduled_program_emails_id_seq from anon, authenticated;

